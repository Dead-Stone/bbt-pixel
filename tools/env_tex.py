def text_px(text, col, row):
    """is font pixel (col,row) of a single-line string set? glyphs 3 wide + 1 gap"""
    if row < 0 or row >= 5 or col < 0: return False
    i, c = divmod(col, 4)
    if i >= len(text) or c == 3: return False
    g = FONT.get(text[i], FONT[' '])
    return g[row][c] == '1'
def text_w(text): return len(text)*4 - 1

def hsh(*a):
    h = 2166136261
    for v in a:
        h = ((h ^ (int(v) & 0xffffffff)) * 16777619) & 0xffffffff
    h ^= h >> 13; h = (h * 0x5bd1e995) & 0xffffffff; h ^= h >> 15
    return (h & 0xffffff) / float(0x1000000)

def line(v, period, width=1/64.0, phase=0.0):
    """1-px line every `period` metres along coordinate v"""
    f = ((v + phase) / period) % 1.0
    return f*period < width

def wood_grain(axis='x', period=0.16, seed=0, top_axis=None):
    """1 px wood_dk streaks every ~8-12 px; broken into dashes"""
    def t(face, x, y, z, tone, rc):
        if face == 'top':
            a = (top_axis or axis)
            v, u = (y, x) if a == 'x' else (x, y)
            k = math.floor(v / period)
            if line(v, period, 1/64.0, 0.37*hsh(seed, k)) and hsh(seed, k, math.floor(u*5)) < 0.65:
                return min(tone + 2, 3)
            return tone
        if line(z, period*0.8, 1/64.0, 0.05*seed) and hsh(seed, math.floor(z/period/0.8), math.floor((x+y)*6)) < 0.6:
            return min(tone + 1, 3)
        return tone
    return t

def merge(*fs):
    def t(face, x, y, z, tone, rc):
        r = None
        for f in fs:
            r = f(face, x, y, z, tone, rc)
            if r is not None and r != tone: return r
        return r
    return t
